'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.env.DESKBOT_PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'artifacts/grok-round-eaf-20261111');
const manifest = JSON.parse(fs.readFileSync(path.join(output, 'manifest.json'), 'utf8'));
const qa = path.join(root, 'tmp/grok-round-eaf-20261111/qa');
let browser;
(async () => {
  fs.mkdirSync(qa, {recursive:true});
  browser = await chromium.launch({headless:true, executablePath:process.env.DESKBOT_BROWSER_EXE ||
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[],external=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url())});
  await page.goto(pathToFileURL(path.join(output,'index.html')).href);
  assert.equal(await page.locator('.card').count(),23);
  assert.equal(manifest.expressions.length,23);
  await page.locator('.card img').first().waitFor({state:'visible'});
  assert(await page.locator('.card img').evaluateAll(async images=>{await Promise.all(images.map(img=>{img.loading='eager';return img.decode()}));return images.every(img=>img.complete&&img.naturalWidth===360)}));
  await page.locator('#commonFilter').click();
  assert.equal(await page.locator('.card').count(),6);
  await page.locator('[data-state="happy"] input').check();
  assert.match(await page.locator('#summary').innerText(),/已选 1 份/);
  await page.locator('#search').fill('害羞');
  assert.equal(await page.locator('.card').count(),1);
  await page.locator('.card button').click();
  assert.match(await page.locator('.card img').getAttribute('src'),/shy\.gif$/);
  assert.equal(await page.locator('.playtag').innerText(),'播放中');
  await page.locator('#pauseAll').click();
  assert.match(await page.locator('.card img').getAttribute('src'),/shy\.png$/);
  await page.locator('#search').fill('');
  assert(await page.locator('[data-state="happy"] input').isChecked());
  await page.locator('#playAll').click();
  assert.equal(await page.locator('.card img').evaluateAll(images=>images.filter(img=>img.src.endsWith('.gif')).length),6);
  await page.locator('#pauseAll').click();
  await page.screenshot({path:path.join(qa,'desktop.png'),fullPage:true});
  await page.locator('#allFilter').click();
  await page.locator('#search').fill('surprised');
  assert.equal(await page.locator('.card').count(),1);
  const download=await page.locator('.card a').getAttribute('href');
  assert(fs.readFileSync(path.join(output,download)).subarray(0,4).equals(Buffer.from([0x89,69,65,70])));
  await page.locator('#search').fill('missing-state');
  assert.equal(await page.locator('.card').count(),0);
  assert.match(await page.locator('.empty').innerText(),/没有匹配/);
  await page.locator('#search').fill('');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#commonFilter').click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(qa,'mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
  const report={result:'passed',scope:'gallery search, filtering, playback, selection, EAF links, 390px layout and offline media',
    expressions:23,common:6,browser_errors:errors,external_requests:external};
  fs.writeFileSync(path.join(qa,'browser-report.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
  await browser.close();
})().catch(async error=>{console.error(error);await browser?.close();process.exitCode=1});
