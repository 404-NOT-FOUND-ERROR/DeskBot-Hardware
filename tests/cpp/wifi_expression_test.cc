#include "wifi_expression.h"
#include <cassert>
#include <iostream>
#include <string>

using namespace deskbot_wifi_expression;
const std::string boot = "boot-" + std::string(32, 'b');
const std::string graph(64, 'c');
std::string Wire(uint64_t sequence = 1, uint64_t query = 100, uint64_t ttl = 3000,
                 uint64_t selection = 4, const char* expression = "happy") {
    return "v1|cmd-" + std::string(24, 'a') + "|" + std::to_string(sequence) + "|" + boot
        + "|" + std::to_string(query) + "|" + std::to_string(ttl) + "|" + graph
        + "|round|" + std::to_string(selection) + "|" + expression + "\n";
}
Command Read(const std::string& wire) { Command c; assert(Decode(wire.data(), wire.size(), c)); return c; }
View Ready() {
    View view{}; std::strcpy(view.binding.graph, graph.c_str()); std::strcpy(view.binding.role, "round");
    view.binding.selection = 4; view.binding.available = true; view.owner_ready = true;
    return view;
}
void Rejects(const std::string& wire) { Command c; assert(!Decode(wire.data(), wire.size(), c)); }

int main(int argc, char** argv) {
    // Node integration invokes this mode with the actual HTTPS response and
    // reads a receipt generated by the production C++ control and encoder.
    if (argc == 3 && !std::strcmp(argv[1], "--receipt")) {
        const auto cmd = Read(argv[2]); View view = Ready();
        std::strcpy(view.binding.graph, cmd.graph); std::strcpy(view.binding.role, cmd.role);
        view.binding.selection = cmd.selection;
        Control control; uint64_t ticket; char semantic[8]{};
        assert(control.Accept(cmd, cmd.boot, cmd.query_ms, cmd.query_ms + 1, view, ticket));
        assert(control.Begin(ticket, cmd.query_ms + 2, view, semantic)); control.Complete(ticket, true);
        char body[800]{}; const std::string device(32, 'a'), fw(64, 'b');
        assert(Encode(body, sizeof(body), device.c_str(), cmd.boot + 5, fw.c_str(), cmd.query_ms + 3,
                      view.binding, false, control.ReadReceipt()));
        std::cout << body; return 0;
    }
    auto wire = Wire(); const auto command = Read(wire); auto view = Ready();
    assert(command.sequence == 1 && command.query_ms == 100 && command.ttl_ms == 3000);
    Rejects(wire.substr(0, wire.size()-1)); Rejects(wire + "extra"); Rejects("v2" + wire.substr(2));
    Rejects(Wire(0)); Rejects(Wire(1, 100, 0)); Rejects(Wire(1, 100, 3001)); Rejects(Wire(1, 100, 3000, 4, "eat"));
    Rejects(Wire(kMaxNumber + 1)); Rejects(Wire(1, 100, 3000, kMaxNumber + 1));
    auto zero = wire; zero.replace(zero.find("|1|"), 3, "|01|"); Rejects(zero);
    auto nul = wire; nul[20] = 0; Rejects(nul);
    auto blank = wire; blank.replace(blank.find("round"), 5, "r  und"); Rejects(blank);
    auto extra = wire; extra.insert(extra.size()-1, "|"); Rejects(extra);
    Control control; uint64_t ticket = 0; char semantic[8]{};
    assert(!control.Accept(command, "boot-other", 100, 101, view, ticket));
    assert(!control.Accept(command, boot.c_str(), 99, 101, view, ticket));
    assert(control.Accept(command, boot.c_str(), 100, 101, view, ticket) && ticket == 1);
    assert(!control.Available());
    uint64_t duplicate = 99;
    assert(control.Accept(command, boot.c_str(), 100, 102, view, duplicate) && duplicate == 0);
    assert(control.Begin(ticket, 200, view, semantic) && !std::strcmp(semantic, "happy"));
    assert(!control.Begin(ticket, 200, view, semantic));
    control.Complete(ticket, true); const auto receipt = control.ReadReceipt();
    assert(receipt.result == Result::Dispatched);
    control.Confirm({}); assert(!control.Available());
    control.Confirm(receipt); assert(control.Available());
    assert(control.Accept(command, boot.c_str(), 100, 300, view, duplicate) && !duplicate);
    assert(control.ReadReceipt().result == Result::Dispatched); control.Confirm(receipt);
    assert(!control.Begin(ticket, 301, view, semantic));
    auto conflict = command; std::strcpy(conflict.expression, "neutral");
    assert(!control.Accept(conflict, boot.c_str(), 100, 302, view, ticket));
    for (auto expected : {Result::OwnerBusy, Result::UsbBusy, Result::BindingChanged, Result::PlayerUnavailable, Result::Expired}) {
        Control c; auto current = Ready(); assert(c.Accept(command, boot.c_str(), 100, 101, current, ticket));
        if (expected == Result::OwnerBusy) current.owner_ready = false;
        if (expected == Result::UsbBusy) current.usb_active = true;
        if (expected == Result::BindingChanged) ++current.binding.selection;
        if (expected == Result::PlayerUnavailable) current.binding.available = false;
        assert(!c.Begin(ticket, expected == Result::Expired ? 3100 : 200, current, semantic));
        assert(c.ReadReceipt().result == expected);
    }
    Control queued; assert(queued.Accept(command, boot.c_str(), 100, 101, view, ticket));
    queued.Expire(3099); assert(queued.ReadReceipt().result == Result::None);
    queued.Expire(3100); assert(queued.ReadReceipt().result == Result::Expired);
    queued.Confirm(queued.ReadReceipt()); assert(!queued.Available());
    auto newer = Read(Wire(2, 3101));
    assert(!queued.Accept(newer, boot.c_str(), 3101, 3102, view, duplicate));
    assert(!queued.Begin(ticket, 3101, view, semantic));
    assert(queued.Available());
    assert(queued.Accept(newer, boot.c_str(), 3101, 3102, view, duplicate) && duplicate == 2);
    Control failed; assert(failed.Accept(command, boot.c_str(), 100, 101, view, ticket));
    assert(failed.Begin(ticket, 200, view, semantic)); failed.Complete(ticket, false);
    assert(failed.ReadReceipt().result == Result::PlayerUnavailable);
    deskbot_role::Details details{}; details.loaded = true; details.count = 1; details.target = 0;
    std::strcpy(details.graph_sha256, graph.c_str()); std::strcpy(details.roles[0], "round"); details.phase = deskbot_role::Phase::Loop;
    assert(CopyBinding(details).available); details.blocked = 1; assert(!CopyBinding(details).available);
    details.blocked = 0; details.asleep = true; assert(!CopyBinding(details).available);
    char body[800]; const std::string device(32, 'a'), fw(64, 'b');
    assert(Encode(body, sizeof(body), device.c_str(), boot.c_str()+5, fw.c_str(), 200, view.binding, true, receipt));
    assert(std::strstr(body, "submitted_to_player") && std::strstr(body, "\"ready\":true"));
    Receipt maximum{}; std::strcpy(maximum.id, "cmd-111111111111111111111111");
    maximum.sequence = kMaxNumber; maximum.result = Result::Dispatched;
    auto maximum_view = view; maximum_view.binding.selection = kMaxNumber;
    assert(Encode(body, sizeof(body), device.c_str(), boot.c_str()+5, fw.c_str(), kMaxNumber,
                  maximum_view.binding, true, maximum));
    assert(std::strstr(body, "\"uptime_ms\":9007199254740991"));
    assert(std::strstr(body, "\"selection\":9007199254740991"));
    assert(std::strstr(body, "\"sequence\":9007199254740991"));
    assert(!Encode(body, 20, device.c_str(), boot.c_str()+5, fw.c_str(), 200, view.binding, true, receipt));
    std::cout << "wifi expression core passed\n";
}
